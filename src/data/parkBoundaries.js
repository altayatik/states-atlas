function parkPoint(id, name, stateCodes, lng, lat, country = 'us') {
  return {
    country,
    geometry: {
      coordinates: [lng, lat],
      type: 'Point',
    },
    id,
    name,
    stateCodes,
    visited: false,
  }
}

