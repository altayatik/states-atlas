export const officialParks = [
  ...usNationalParks.map((park) => ({ ...park, country: 'us' })),
  ...canadianNationalParks,
]

export function getOfficialParkByName(name) {
  const normalizedName = name?.replace(/\s+National Park$/i, '').trim()
  return officialParks.find((park) => park.name === name || park.name === normalizedName)
}

export function getOfficialParksByCountry(country) {
  return officialParks.filter((park) => park.country === country)
}

export function getOfficialParkCountry(name) {
  return getOfficialParkByName(name)?.country ?? 'custom'
}

export function getOfficialParkDisplayName(name) {
  const officialPark = getOfficialParkByName(name)
  if (!officialPark) return name
  if (/^National Park of\b/i.test(officialPark.name) || /\bNational Park\b/i.test(officialPark.name)) {
    return officialPark.name
  }

  return `${officialPark.name} National Park`
}
